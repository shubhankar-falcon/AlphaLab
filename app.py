"""AlphaLab research dashboard (entirely synthetic data in v0.1)."""

import streamlit as st

from alphalab.data.demo import DemoPriceProvider
from alphalab.strategies.momentum import screen_momentum

st.set_page_config(page_title="AlphaLab | Strategy Research", page_icon="📈", layout="wide")


@st.cache_data
def load_prices():
    """One reproducible dataset, cached across widget interactions."""
    return DemoPriceProvider().get_prices()


st.title("AlphaLab")
st.caption("Indian equities · Strategy research sandbox · v0.1")
st.warning(
    "DEMO ONLY — all prices and performance figures are synthetic. "
    "No live data, recommendations, orders, or real returns."
)

with st.sidebar:
    st.header("Screener settings")
    lookback = st.selectbox(
        "Momentum lookback (trading sessions)",
        options=[21, 63, 126, 252],
        index=2,
        help="Approximately 1, 3, 6, or 12 trading months.",
    )
    top_n = st.slider("Number of stocks", min_value=5, max_value=15, value=10)
    st.divider()
    st.caption("Data source: deterministic synthetic sample")

prices = load_prices()
results = screen_momentum(prices, lookback_sessions=lookback, top_n=top_n)
as_of = prices["date"].max().date().isoformat()

left, middle, right = st.columns(3)
left.metric("Sample universe", f"{prices['ticker'].nunique()} symbols")
middle.metric("Latest demo date", as_of)
right.metric("Ranked stocks", str(len(results)))

st.subheader("Momentum stock screener")
st.write(
    "Stocks ranked by **trailing price return** over the chosen period. "
    "Historical return is not a forecast or an investment recommendation."
)
if results.empty:
    st.info("No stocks have sufficient usable history for this selection.")
else:
    st.dataframe(
        results.style.format(
            {
                "momentum_pct": "{:+.2f}%",
                "volatility_pct": "{:.2f}%",
                "last_close": "{:.2f}",
            }
        ),
        hide_index=True,
        use_container_width=True,
    )

    st.subheader("Explore a synthetic price series")
    selected = st.selectbox("Ticker", results["ticker"].tolist())
    ticker_prices = prices.loc[prices["ticker"] == selected, ["date", "close"]]
    st.line_chart(ticker_prices.set_index("date")["close"], y_label="Synthetic price")

with st.expander("Research methodology and limitations"):
    st.markdown(
        """
        - Momentum = (last close / close **N sessions earlier** − 1) × 100.
        - Volatility = sample standard deviation of daily returns × √252 × 100.
        - Stocks without enough prices, or with stale last dates, are excluded.
        - This is a **screener**, not a backtest; no rebalancing, trading costs,
          dividends, survivorship-bias treatment, or benchmark calculation yet.
        - All input prices are generated by a fixed random seed for reproducibility.
        """
    )
